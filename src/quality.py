"""Data quality report for the master dataset, written as Markdown for the repo."""
import re

import pandas as pd

FAMILIES = {
    "core": r"^(TransactionAmt|ProductCD|TransactionDT)$",
    "card": r"^card\d$",
    "address / distance": r"^(addr\d|dist\d)$",
    "email domain": r"^[PR]_emaildomain$",
    "C (counts)": r"^C\d+$",
    "D (time gaps)": r"^D\d+$",
    "M (match flags)": r"^M\d$",
    "V (Vesta engineered)": r"^V\d+$",
    "identity": r"^(id_\d+|DeviceType|DeviceInfo)$",
}


def family_missingness(df):
    rows = []
    for fam, pattern in FAMILIES.items():
        cols = [c for c in df.columns if re.match(pattern, c)]
        if not cols:
            continue
        miss = df[cols].isna().mean()
        rows.append({
            "family": fam,
            "columns": len(cols),
            "avg_missing": f"{miss.mean():.1%}",
            "worst_column": f"{miss.idxmax()} ({miss.max():.1%})",
        })
    return pd.DataFrame(rows)


def by_split(df):
    fraud_amount = df["TransactionAmt"] * df["isFraud"]
    by = df.groupby("split", observed=True)
    out = pd.DataFrame({
        "transactions": by.size(),
        "fraud_rate": by["isFraud"].mean().map("{:.2%}".format),
        # share of the money that was fraud, as opposed to the share of transactions
        "fraud_value_share": (fraud_amount.groupby(df["split"], observed=True).sum()
                              / by["TransactionAmt"].sum()).map("{:.2%}".format),
        "first_day": by["day"].min(),
        "last_day": by["day"].max(),
    })
    return out.reindex(["train", "valid", "oot"])


def by_month(df):
    by = df.groupby("month", observed=True)
    return pd.DataFrame({
        "transactions": by.size(),
        "fraud_rate": by["isFraud"].mean().map("{:.2%}".format),
    })


def checks(df):
    return {
        "rows": f"{len(df):,}",
        "columns": df.shape[1],
        "duplicate TransactionID": int(df["TransactionID"].duplicated().sum()),
        "missing label": int(df["isFraud"].isna().sum()),
        "overall fraud rate": f"{df['isFraud'].mean():.2%}",
        "transactions with identity data": f"{df['has_identity'].mean():.1%}",
        "TransactionAmt <= 0": int((df["TransactionAmt"] <= 0).sum()),
        "TransactionAmt max": f"{df['TransactionAmt'].max():,.2f}",
        "days covered": f"{df['day'].min()} to {df['day'].max()}",
        "memory (MB)": round(df.memory_usage(deep=True).sum() / 1e6, 1),
    }


def write_report(df, uid_stats, path):
    lines = ["# Data quality report: IEEE-CIS master dataset", "",
             "Generated by `scripts/build_master.py`. All figures are from the labelled training data.", "",
             "## Basic checks", "", "| Check | Result |", "| --- | --- |"]
    lines += [f"| {k} | {v} |" for k, v in checks(df).items()]
    lines += ["", "## Time split", "", by_split(df).to_markdown(), "",
              "## Fraud rate by month", "", by_month(df).to_markdown(), "",
              "## Missing values by feature family", "", family_missingness(df).to_markdown(index=False), "",
              "## Rebuilt customer ID", "", "| Check | Result |", "| --- | --- |"]
    lines += [f"| {k.replace('_', ' ')} | {v} |" for k, v in uid_stats.items()]
    lines += ["", "## Notes", "",
              "- Missing values are not errors here: many columns only apply to some products "
              "or to transactions with identity data.",
              "- Missingness patterns are themselves predictive, so they are kept, not imputed away, "
              "for tree models.",
              ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))
