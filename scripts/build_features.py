"""
Step 3: build the modelling feature table and the feature report.

Run after scripts/build_master.py and scripts/build_velocity.py:
  python scripts/build_features.py

Outputs:
  data/processed/features.parquet   one row per transaction, all model features
  reports/feature_report.md         feature groups, V reduction, information value ranking
"""
import sys
import time
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.features import build_features, iv_table  # noqa: E402

DESCRIPTIONS = {
    "base": "Named transaction fields: amount (plus log, cents, round-amount flag), time, product, card, address, "
            "email domain, C/D/M families, identity fields",
    "missingness": "How many V / D / M / identity fields are missing, and how many M match flags are true",
    "email": "Email provider and suffix, purchaser vs recipient domain match",
    "device": "Device, operating system and browser family (coarse groups)",
    "d_normalised": "day - D for D4, D10, D11, D15: turns 'days since' into stable start dates",
    "frequency": "How common the card, address, email, device or fingerprint is (training months)",
    "target_encoding": "Smoothed fraud rate for email domains, card type x product, device family, address "
                       "(out-of-fold on training rows, training-fitted for later months)",
    "customer_history": "Customer's average of C1, C13, C14, D15, dist1 over EARLIER transactions",
    "device_sharing": "Customers per device fingerprint (training months); fingerprint new for this customer",
    "vesta_v_reduced": "Vesta-engineered V columns after removing near-duplicates",
    "velocity": "Step 2 SQL features: transaction counts and spend in the last 1h / 24h / 7d, gaps, newness",
}


def main():
    t0 = time.time()
    master = pd.read_parquet("data/processed/master.parquet")
    velocity = pd.read_parquet("data/processed/velocity.parquet")
    feats, meta = build_features(master, velocity)
    del master
    print(f"Built {feats.shape[1] - 5} features for {len(feats):,} transactions ({time.time() - t0:.0f}s)")

    out = Path("data/processed/features.parquet")
    feats.to_parquet(out, index=False)

    iv = iv_table(feats, meta["groups"])
    print(f"Information value computed ({time.time() - t0:.0f}s)")
    group_rows = "\n".join(f"| {g} | {len(c)} | {DESCRIPTIONS[g]} |" for g, c in meta["groups"].items())
    summary = iv.groupby("strength", observed=False).size().to_frame("features").to_markdown()

    Path("reports/feature_report.md").write_text("\n".join([
        "# Feature report", "",
        "Generated by `scripts/build_features.py`. Information value (IV) is measured on training months only.", "",
        f"**{feats.shape[1] - 5} features** for {len(feats):,} transactions.", "",
        "## Feature groups", "", "| Group | Features | What it captures |", "| --- | --- | --- |", group_rows, "",
        "## V column reduction", "",
        f"{meta['v_total']} V columns, grouped into {meta['v_groups']} blocks that share a missing-value pattern. "
        f"Within each block, one of any pair correlated above 0.75 was kept: **{meta['v_kept']} kept**.", "",
        "## Information value", "",
        "IV < 0.02 useless, 0.02-0.1 weak, 0.1-0.3 medium, 0.3-0.5 strong. Above 0.5 is unusually high "
        "and should be checked for leakage.", "",
        summary, "",
        "### Top 30 features", "",
        iv.head(30).assign(iv=iv["iv"].round(3)).to_markdown(index=False), "",
        "### Weakest 10", "",
        iv.tail(10).assign(iv=iv["iv"].round(4)).to_markdown(index=False), "",
    ]))
    iv.to_csv("reports/feature_iv.csv", index=False)
    print(iv.head(15).to_string(index=False))
    print(f"Saved {out}, reports/feature_report.md, reports/feature_iv.csv ({time.time() - t0:.0f}s)")


if __name__ == "__main__":
    main()
