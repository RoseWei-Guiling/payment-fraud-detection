"""
Check features with very high information value (IV > 0.5) for leakage.

Three tests per feature:
  1. Train vs validation IV. A leak only exists where the feature was built with labels it
     shouldn't have seen, so its signal collapses on later months. Real signal holds up.
  2. Is the signal just "missing or not"? IV with the missing rows removed, and the fraud
     rate when the value is missing vs present.
  3. Is it just the product code? IV inside the largest product (W) only.

  python scripts/check_high_iv.py
Writes reports/high_iv_check.md
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.features import information_value  # noqa: E402

THRESHOLD = 0.5


def main():
    iv = pd.read_csv("reports/feature_iv.csv")
    flagged = iv.loc[iv["iv"] > THRESHOLD, "feature"].tolist()
    # dict.fromkeys drops duplicates while keeping order (ProductCD can itself be flagged)
    columns = list(dict.fromkeys(["isFraud", "split", "ProductCD"] + flagged))
    feats = pd.read_parquet("data/processed/features.parquet", columns=columns)
    train = feats[feats["split"] == "train"]
    valid = feats[feats["split"] == "valid"]
    main_product = train["ProductCD"].astype("string").value_counts().index[0]

    rows = []
    for f in flagged:
        present = train[f].notna()
        in_main_product = train["ProductCD"].astype("string") == main_product
        iv_train = information_value(train[f], train["isFraud"])
        iv_valid = information_value(valid[f], valid["isFraud"])
        rows.append({
            "feature": f,
            "iv_train": round(iv_train, 3),
            "iv_valid": round(iv_valid, 3),
            "valid_vs_train": f"{iv_valid / iv_train:.0%}" if iv_train else "n/a",
            "missing_share": f"{1 - present.mean():.0%}",
            "fraud_if_missing": f"{train.loc[~present, 'isFraud'].mean():.1%}" if (~present).any() else "n/a",
            "fraud_if_present": f"{train.loc[present, 'isFraud'].mean():.1%}",
            "iv_without_missing": round(information_value(train.loc[present, f], train.loc[present, "isFraud"]), 3),
            f"iv_within_{main_product}": round(information_value(train.loc[in_main_product, f],
                                                                 train.loc[in_main_product, "isFraud"]), 3),
        })
    table = pd.DataFrame(rows).sort_values("iv_train", ascending=False)

    Path("reports/high_iv_check.md").write_text("\n".join([
        f"# Leakage check: features with IV above {THRESHOLD}", "",
        "Generated by `scripts/check_high_iv.py`.", "",
        "- **valid_vs_train** near 100%: the signal holds on later months (real). A big drop "
        "(say under 50%) points to leakage or overfitting.",
        "- **iv_without_missing** much lower than iv_train: most of the signal is 'value missing or not'.",
        f"- **iv_within_{main_product}** much lower: the feature mostly re-tells the product code.", "",
        table.to_markdown(index=False), "",
    ]))
    print(table.to_string(index=False))
    print("Saved reports/high_iv_check.md")


if __name__ == "__main__":
    main()
