"""
Step 2a: build customer velocity features and prove the SQL and pandas versions agree.

Runs on your laptop, no cloud needed: the SQL is executed with DuckDB, the same SQL
that scripts/bigquery_features.py runs in BigQuery.

  python scripts/build_velocity.py

Outputs:
  data/processed/velocity.parquet   one row per transaction, 10 velocity features
  reports/velocity_check.md         SQL vs pandas match table + first look at the signal
"""
import sys
import time
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.velocity import compare, velocity_features, velocity_features_duckdb  # noqa: E402

MASTER = Path("data/processed/master.parquet")
OUT = Path("data/processed/velocity.parquet")
REPORT = Path("reports/velocity_check.md")


def signal_table(df, feat, bins, labels):
    """Fraud rate by feature bucket, training months only (never peek at the test months)."""
    train = df[df["split"] == "train"]
    bucket = pd.cut(train[feat], bins=bins, labels=labels, right=False)
    t = train.groupby(bucket, observed=True)["isFraud"].agg(transactions="size", fraud_rate="mean")
    t["fraud_rate"] = t["fraud_rate"].map("{:.2%}".format)
    return t.to_markdown()


def main():
    t0 = time.time()
    master = pd.read_parquet(MASTER, columns=["TransactionID", "TransactionDT", "TransactionAmt", "uid",
                                              "uid_complete", "DeviceInfo", "P_emaildomain", "isFraud", "split"])
    pandas_feats = velocity_features(master)
    print(f"pandas features: {time.time() - t0:.0f}s")
    sql_feats = velocity_features_duckdb(master)
    print(f"SQL (DuckDB) features: {time.time() - t0:.0f}s")

    check = compare(pandas_feats, sql_feats)
    print(check.to_string(index=False))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    pandas_feats.to_parquet(OUT, index=False)

    df = master[["TransactionID", "isFraud", "split"]].merge(pandas_feats, on="TransactionID")
    lines = [
        "# Velocity features: SQL vs pandas check", "",
        "Generated by `scripts/build_velocity.py`. The same SQL file (`sql/velocity_features.sql`) runs in DuckDB here "
        "and in BigQuery via `scripts/bigquery_features.py`.", "",
        f"**All features match: {bool(check['match'].all())}** ({len(df):,} transactions)", "",
        check.to_markdown(index=False), "",
        "## First look at the signal (training months only)", "",
        "### Customer's transactions in the previous 24 hours", "",
        signal_table(df, "uid_n_24h", [0, 1, 2, 5, float("inf")], ["0", "1", "2-4", "5+"]), "",
        "### Customer's transaction number (1 = first time seen)", "",
        signal_table(df, "uid_txn_number", [1, 2, 3, 6, float("inf")], ["1st", "2nd", "3rd-5th", "6th+"]), "",
        "### New device for an existing customer", "",
        signal_table(df, "new_device_for_uid", [0, 1, 2], ["seen before", "new"]), "",
        "### Amount vs the customer's usual amount", "",
        signal_table(df, "amt_to_uid_mean", [0, 0.5, 2, 5, float("inf")], ["< 0.5x", "0.5-2x", "2-5x", "5x+"]), "",
    ]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines))
    print(f"Saved {OUT} and {REPORT} ({time.time() - t0:.0f}s)")
    if not check["match"].all():
        sys.exit("SQL and pandas disagree: see the table above.")


if __name__ == "__main__":
    main()
