"""
Step 8: write investigator case notes for the test month's riskiest blocked payments.

  python scripts/write_case_notes.py                  # template notes (no API key needed)
  export ANTHROPIC_API_KEY=...                        # optional: notes written by Claude,
  python scripts/write_case_notes.py --llm            # checked so they contain no invented numbers

Output: reports/case_notes.md
"""
import argparse
import os
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.case_notes import case_facts, write_note  # noqa: E402
from src.scoring import Scorer  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--llm", action="store_true", help="write notes with Claude (needs ANTHROPIC_API_KEY)")
    ap.add_argument("--model", default="claude-haiku-4-5-20251001")
    ap.add_argument("--n", type=int, default=5)
    args = ap.parse_args()

    client = None
    if args.llm:
        if not os.environ.get("ANTHROPIC_API_KEY"):
            sys.exit("Set ANTHROPIC_API_KEY first, or run without --llm for template notes.")
        import anthropic
        client = anthropic.Anthropic()

    scorer = Scorer()
    names = scorer.config["features"]
    scores = pd.read_parquet("data/processed/model_scores.parquet", columns=["TransactionID", "split", "lightgbm",
                                                                             "TransactionAmt", "isFraud"])
    oot = scores[scores["split"] == "oot"].copy()
    oot["expected_loss"] = oot["lightgbm"] * oot["TransactionAmt"]
    picked = oot.sort_values("expected_loss", ascending=False).head(args.n)  # biggest money at stake

    feats = pd.read_parquet("data/processed/features.parquet")
    rows = feats.set_index("TransactionID").loc[picked["TransactionID"]]
    payments = [{"TransactionID": int(tid), **{k: (None if pd.isna(v) else (v.item() if hasattr(v, "item") else v))
                                               for k, v in r[names].items()}}
                for tid, r in rows.iterrows()]
    results = scorer.score(payments)

    lines = ["# Investigator case notes", "",
             "Generated by `scripts/write_case_notes.py` for the test month's blocked payments with the most money "
             "at stake (probability of fraud x amount). The facts are built from the data; "
             + ("Claude rewrites them into a note, and any note containing a number that is not in the facts is "
                "replaced by the template." if client else "notes use a fixed template (run with `--llm` for "
                                                            "notes written by Claude)."), ""]
    for payment, result, (_, truth) in zip(payments, results, picked.iterrows()):
        facts = case_facts(payment, result)
        note, source = write_note(facts, client, args.model)
        lines += [f"## Payment {payment['TransactionID']}", "",
                  note, "",
                  f"*Written by: {source}. Actual outcome (known here, not to the investigator): "
                  f"{'fraud' if truth['isFraud'] else 'genuine'}.*", ""]
        print(f"{payment['TransactionID']}: {source}")
    Path("reports/case_notes.md").write_text("\n".join(lines))
    print("Saved reports/case_notes.md")


if __name__ == "__main__":
    main()
