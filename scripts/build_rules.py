"""
Step 4: evaluate the candidate rules, choose the champion rule set, and report.

  python scripts/build_rules.py

Rules are chosen on the TRAINING months and judged on the VALIDATION month.
The out-of-time test month is not looked at until Step 7.

Outputs:
  reports/rules_report.md            every rule in plain English with its numbers, the chosen set, train vs validation
  data/processed/rules_flags.parquet which rules fired on every payment (used to compare against the models)
"""
import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.rules import fire_all, load_rules, metrics, rule_columns, rule_table, rules_score, select_rules  # noqa: E402


def pct_columns(table):
    out = table.copy()
    for col in ["decline_rate", "fraud_caught", "fraud_value_caught", "precision", "precision_of_new_flags"]:
        if col in out:
            out[col] = out[col].map(lambda v: "" if pd.isna(v) else f"{v:.1%}")
    if "false_positive_ratio" in out:
        out["false_positive_ratio"] = out["false_positive_ratio"].map(lambda v: f"{v:.1f}")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-precision", type=float, default=0.10,
                    help="only add a rule if at least this share of its new flags are fraud")
    ap.add_argument("--max-decline-rate", type=float, default=0.05,
                    help="never flag more than this share of all payments")
    args = ap.parse_args()

    rules = load_rules()
    cols = ["TransactionID", "isFraud", "split", "TransactionAmt"] + rule_columns(rules)
    df = pd.read_parquet("data/processed/features.parquet", columns=list(dict.fromkeys(cols)))
    fired = fire_all(df, rules)
    train, valid = (df["split"] == "train").to_numpy(), (df["split"] == "valid").to_numpy()

    def on(mask):
        return fired[mask], df.loc[mask, "isFraud"], df.loc[mask, "TransactionAmt"]

    per_rule_train = rule_table(*on(train))
    per_rule_valid = rule_table(*on(valid))
    chosen, log = select_rules(fired[train], df.loc[train, "isFraud"],
                               args.min_precision, args.max_decline_rate)

    champion = fired[chosen].any(axis=1) if chosen else pd.Series(False, index=df.index)
    summary = pd.DataFrame([
        {"months": "train (rules chosen here)", **metrics(champion[train], df.loc[train, "isFraud"],
                                                          df.loc[train, "TransactionAmt"])},
        {"months": "validation (judged here)", **metrics(champion[valid], df.loc[valid, "isFraud"],
                                                         df.loc[valid, "TransactionAmt"])},
    ])

    flags = pd.concat([df[["TransactionID", "split", "isFraud"]], fired], axis=1)
    flags["champion_flag"] = champion.astype("int8")
    flags["rules_fired"] = rules_score(fired, chosen).astype("int8")
    flags.to_parquet("data/processed/rules_flags.parquet", index=False)

    meaning = pd.DataFrame([{"rule": r["name"], "condition": f"`{r['condition']}`", "meaning": r["meaning"],
                             "why we tried it": r["why"]} for r in rules])
    Path("reports/rules_report.md").write_text("\n".join([
        "# Rules champion", "",
        "Generated by `scripts/build_rules.py`. Rules are in `rules/champion_rules.yaml`. "
        "Chosen on training months, judged on the validation month.", "",
        "**How to read the numbers:** *decline rate* = share of all payments the rule blocks; "
        "*fraud caught* = share of fraud payments it blocks; *precision* = share of its blocks that are "
        "really fraud; *false-positive ratio* = genuine payments blocked per fraud caught.", "",
        f"## Champion rule set: {len(chosen)} rules", "",
        ", ".join(f"`{name}`" for name in chosen) or "(none passed the bar)", "",
        pct_columns(summary).to_markdown(index=False), "",
        "## How the set was chosen (training months)", "",
        f"Greedy: keep adding the rule whose new flags are most often fraud, while at least "
        f"{args.min_precision:.0%} of those new flags are fraud and the set flags at most "
        f"{args.max_decline_rate:.0%} of payments.", "",
        pct_columns(log).to_markdown(index=False), "",
        "## Every rule on its own: validation month", "",
        pct_columns(per_rule_valid).to_markdown(index=False), "",
        "## Every rule on its own: training months", "",
        pct_columns(per_rule_train).to_markdown(index=False), "",
        "## The rules in plain English", "",
        meaning.to_markdown(index=False), "",
    ]))
    print(pct_columns(per_rule_valid).to_string(index=False), "\n")
    print("Champion rules:", chosen)
    print(pct_columns(summary).to_string(index=False))
    print("Saved reports/rules_report.md and data/processed/rules_flags.parquet")


if __name__ == "__main__":
    main()
